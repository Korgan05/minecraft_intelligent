        self._zdorovyj = o                  # опора для подстановки на заминках
        self._v_mire_nastoyashchij = True
        # Тип противника этого боя — в ленту: победы по мечникам и по простым
        # должны быть видны отдельно, иначе забывание одного из них не заметить.
        self.protivnik = "+".join(A.POSLEDNIJ_SOSTAV) or "человек"
        # Память заполняем ОДНИМ И ТЕМ ЖЕ кадром: в начале боя движения ещё нет,
        # и честнее показать неподвижность, чем обрывки прошлого боя.
        self._pamyat = [o["kadr"].copy()] * GLUBINA_BUFERA
        self._posl = o
        self.pred = A.schet_boya(self.k, self.igrok)
