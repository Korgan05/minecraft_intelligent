class ZamorozkaNaObuchenie(BaseCallback):
    """Замораживает зомби, пока мозг учится. Иначе бой идёт без существа.

    НАЙДЕНО ЗАМЕРОМ, а не догадкой. SB3 синхронен: собрал пачку — считает
    обновление, и на это время среда не получает ни одного действия. А Minecraft
    живёт в реальном времени: зомби ходит и бьёт, существо стоит столбом.

    Длину паузы посчитал из самих лент — там у каждого боя есть отметка времени,
    и лишнее время (часы минус шаги по 0.205 с) выдаёт паузу:
        бои, внутри которых шло обучение : лишнего  9.5 с
        остальные бои                    : лишнего  0.9 с
        то есть пауза примерно 8.7 секунды, а в отдельных боях +14 и +25
    Зомби бьёт около 3 HP в секунду, значит девять секунд — это до 27 HP по
    стоячему существу из его сорока.

    Что это НЕ объясняет, чтобы не преувеличивать: обновление режет примерно один
    бой из двадцати, поэтому на долю убийств за прогон это почти не влияет
    (по девяти таким боям смертей 22% против 13%, но p = 0.337 — не отличить).

    Что это портит по-настоящему: те девять секунд побоев попадают в пачку как
    награда за действие, которое было послано последним. Отравленный образец,
    и притом ровно один на обновление — как раз там, где мы искали причину срывов.

    Крючки выбраны по установленному исходнику: on_rollout_end вызывается на
    строке 266 on_policy_algorithm.py, а train() — на 337. То есть между ними и
    сидит пауза. on_rollout_start (строка 192) отпускает зомби перед сбором.
    """

    def __init__(self):
        super().__init__()
        self.zamorozok = 0
        self.sboev = 0

    def _konsol(self):
        return self.training_env.envs[0].unwrapped.k

    def _on_rollout_end(self) -> None:
        if A.zamorozit_vseh(self._konsol(), True):
            self.zamorozok += 1
        else:
            self.sboev += 1
            print("  !!! не удалось заморозить зомби перед обучением — "
                  "бой пойдёт без существа", flush=True)

    def _on_rollout_start(self) -> None:
        if self.zamorozok and not A.zamorozit_vseh(self._konsol(), False):
            # Хуже некуда: зомби остался замороженным, и в логе будут прекрасные
            # 100% побед при обучении впустую. Лучше упасть.
            raise RuntimeError("зомби остались замороженными после обучения")

    def _on_step(self) -> bool:
        return True


class Lenta(BaseCallback):
    """Что происходит в бою: убийства, итоги жизней, редкие сводки.

    Заодно сторожит качество и останавливает обучение, если оно поехало вниз.
    """

    def __init__(self):
        super().__init__()
        self.itogi = []              # True за победу, False за смерть
        self.dliny = []              # длина каждого боя в шагах
        # НАГРАДА ЗА БОЙ ПРЯМО В ЛЕНТУ. Именно этот замер решил спор «виновата
        # арифметика или обучение», и мне пришлось ВОССТАНАВЛИВАТЬ его из ленты по
        # слагаемым — приближённо, без платы за простой. Теперь пишем настоящее
        # число, которое видит мозг: спор в следующий раз решится одной строкой.
        self.nagrada_boya = 0.0
        self.ploho_podryad = 0       # сколько плохих окон подряд насчитал сторож
        self.boj = 0
        self.ubijstv_vsego = 0
        self.uron_boya = 0.0
        self.shagov_boya = 0
        self.rekord = 0.0
        self.smertej = 0
        self.pitch_udar = self.pitch_bol = 0.0
        self.udarov = self.bolej = 0
        # СУД ПО ТИПАМ. Смешанный сторож слеп к порче одного навыка: 98% на
        # простых прячут 13% на мечниках (случилось 31.07: смешанное окно
        # держалось выше порога, пока дуэль умирала). Отдельное окно по
        # мечниковым боям видит это сразу. Порог 30% — перебор на 182 опорных
        # мечниковых боях (47.3%): ноль ложных, худшее окно 40%.
        self.itogi_mechnika = []
        self.ploho_mechnik = 0

    def _pishi(self, tekst):
        print(tekst, flush=True)
        with open(LENTA, "a", encoding="utf-8") as f:
            f.write(f"[{datetime.now():%d.%m %H:%M:%S}] {tekst}\n")

    def _on_step(self) -> bool:
        infos = self.locals.get("infos") or [{}]
        inf = infos[0] or {}
        self.uron_boya += float(inf.get("uron", 0.0))
        if inf.get("pitch_udar") is not None:
            self.pitch_udar += float(inf["pitch_udar"])
            self.udarov += 1
        if inf.get("pitch_bol") is not None:
            self.pitch_bol += float(inf["pitch_bol"])
            self.bolej += 1
        self.shagov_boya += 1
        nagr = self.locals.get("rewards")
        if nagr is not None:
            self.nagrada_boya += float(np.asarray(nagr).reshape(-1)[0])
        # Следим за здоровьем: без этого нельзя было проверить, добивает ли
        # существо зомби полудохлым. Раньше в логе был только нанесённый урон.
        zh = inf.get("zhizn")
        if zh is not None:
            self.zhizn_konec = float(zh)
            self.zhizn_min = min(getattr(self, "zhizn_min", 999.0), float(zh))
        if inf.get("kill"):
            self.ubijstv_vsego += 1
            self._pishi(f"*** УБИЛ ЗОМБИ #{self.ubijstv_vsego} *** "
                        f"(шаг {self.num_timesteps}, бой {self.boj + 1})")
        dones = self.locals.get("dones")
        if dones is not None and np.any(dones):
            self.boj += 1
            pogib = bool(inf.get("death"))
            self.smertej += 1 if pogib else 0
            self.rekord = max(self.rekord, self.uron_boya)
            itog = "УБИЛ" if inf.get("kill") else (
                "погиб" if pogib else "не успел")
            self.itogi.append(bool(inf.get("kill")))
            if inf.get("protivnik") == "мечник":
                self.itogi_mechnika.append(bool(inf.get("kill")))
            zh_min = getattr(self, "zhizn_min", float("nan"))
            # Опоздания шага пишем только когда они есть: у мода клавиши держатся
            # до следующего заказа, поэтому растянутый шаг растягивает и нажатия,
            # то есть меняет среду на ходу. Без этой отметки такой срыв потом не
            # отличить от порчи политики.
            opozd = int(inf.get("opozdanij") or 0)
            hvost = f" | против {inf.get('protivnik', '?')}"
            hvost += f" | ОПОЗДАНИЙ {opozd}" if opozd else ""
            # Взгляд: средний за бой, крайний, доля шагов у самого упора (+75 и
            # ниже — это почти в пол), и отдельно куда смотрел в моменты урона.
            # Плюс = ВНИЗ. Если средний уползает к +60..90, а доля у упора велика,
            # значит канал взгляда — трещотка, и дело не в настройках обучения.
            pu = self.pitch_udar / \
                max(self.udarov, 1) if self.udarov else float("nan")
            pb = self.pitch_bol / \
                max(self.bolej, 1) if self.bolej else float("nan")
            hvost += (f" | взгляд сред {inf.get('pitch_sred', float('nan')):+5.1f}"
                      f" макс {inf.get('pitch_max', float('nan')):+5.1f}"
                      f" у упора {100 * (inf.get('pitch_upor') or 0):3.0f}%"
                      f" при ударе {pu:+5.1f} при боли {pb:+5.1f}")
            self._pishi(f"бой #{self.boj}: {itog} | НАГРАДА {self.nagrada_boya:+7.2f} | "
                        f"урон {self.uron_boya:5.1f} HP | "
                        f"здоровье минимум {zh_min:4.0f} | шагов {self.shagov_boya:3d} | "
                        f"убийств {self.ubijstv_vsego} | смертей {self.smertej}/{self.boj}"
                        f"{hvost}")
            self.nagrada_boya = 0.0
            self.dliny.append(self.shagov_boya)
            self.uron_boya, self.shagov_boya = 0.0, 0
            self.zhizn_min = 999.0
            self.pitch_udar = self.pitch_bol = 0.0
            self.udarov = self.bolej = 0
            if self.boj >= NE_SUDIT_RANSHE and not getattr(self, "storozh_vyklyuchen", False):
                posl = self.itogi[-SLEDIT_ZA_POSLEDNIMI:]
                dolya = sum(posl) / len(posl)
                nachalo = sum(self.dliny[:NACHALO_DLINY]) / \
                    min(len(self.dliny), NACHALO_DLINY)
                teper = sum(self.dliny[-SLEDIT_ZA_POSLEDNIMI:]) / len(posl)
                prichina = None
                if dolya < HUZHE_CHEM:
                    prichina = (f"за последние {len(posl)} боёв убийств "
                                f"{100 * dolya:.0f}%, ниже порога {100 * HUZHE_CHEM:.0f}%")
                # Длина боя растёт раньше, чем падают убийства.
                elif nachalo > 0 and teper > nachalo * DLINNEE_CHEM:
                    prichina = (f"бои удлинились с {nachalo:.0f} до {teper:.0f} шагов "
                                f"({teper / nachalo:.2f}x при пороге {DLINNEE_CHEM}x), "
                                f"убийств пока {100 * dolya:.0f}%")
                self.ploho_podryad = self.ploho_podryad + 1 if prichina else 0
                if len(self.itogi_mechnika) >= 30 and not getattr(self, "storozh_vyklyuchen", False):
                    dm = sum(self.itogi_mechnika[-30:]) / 30
                    if dm < 0.30:
                        self.ploho_mechnik += 1
                        if self.ploho_mechnik >= PODRYAD_PLOHIH:
                            self._pishi(
                                f"!!! СТОРОЖ ДУЭЛИ ОСТАНАВЛИВАЕТ: за последние 30 боёв с мечником "
                                f"побед {100 * dm:.0f}%, ниже порога 30%. Дуэль разучивается — "
                                "останавливаюсь и сохраняю.")
                            return False
                    else:
                        self.ploho_mechnik = 0
                if self.ploho_podryad >= PODRYAD_PLOHIH:
                    self._pishi(
                        f"!!! СТОРОЖ ОСТАНАВЛИВАЕТ: {prichina}. "
                        f"Так {self.ploho_podryad} окна подряд — это не случайность. "
                        "Останавливаюсь и сохраняю. Вернись к снимку получше: "
                        "снимки лежат в models\\ubijca_ckpt_*_steps.zip.")
                    return False
        return True


def main():
    p = argparse.ArgumentParser()
    p.add_argument("--shagov", type=int, default=2_000_000)
    # РАЗМЕР ШАГА. Было 2.5e-4 — и это оказалось главной причиной срывов, а не
    # арифметика награды, на которую я потратил два дня.
    #
    # Что показали приборы прошлого прогона (разобран tfevents вручную):
    #   * ОДИН шаг градиента уводил политику на approx_kl >= 0.2237 при пороге
    #     поводка 1.5*0.02 = 0.03, то есть в 7.5 раза дальше допустимого;
    #   * поэтому поводок не удерживал, а РВАЛ обновление после первой же порции:
    #     счётчик Adam за весь прогон 2240 -> 2243, то есть РОВНО ТРИ шага
    #     градиента на 6564 шага среды, и 87.5% собранного опыта выброшено;
    #   * обрыв выходит и из цикла порций, и из цикла эпох, поэтому оценщик
    #     получал те же три шага: explained_variance -0.02 и -0.07, хуже, чем
    #     предсказывать константу. Замкнутый круг: оценщик не работает ->
    #     преимущества это сырая отдача с огромным разбросом -> KL за шаг растёт;
    #   * и главное: ПЕРВОЕ ЖЕ обновление — по пачке из 22 убийств при НУЛЕ
    #     смертей — уже дало KL 0.2237. Смерть тут не при чём.
    #
    # 8e-5 получено из квадратичности KL по размеру шага:
    #     2.5e-4 * sqrt(0.03 / 0.2237) = 9.2e-5, берём с запасом.
    # Это ЭКСТРАПОЛЯЦИЯ, а не замер: подтвердит её только новый прогон. Смотреть
    # надо на train/approx_kl — он обязан стать <= 0.03 на канал.
    p.add_argument("--lr", type=float, default=8e-5)
    # БОНУС ЗА НЕУВЕРЕННОСТЬ. Стоял 0.02 со времён, когда действие было одним
    # выбором из двадцати. При каналах энтропия СКЛАДЫВАЕТСЯ по всем шести, и
    # её максимум вырос с 3.00 до 7.68 — то есть давление на случайность
    # выросло в 2.6 раза само собой, без нашего решения. Существо стало
    # получать за случайность вклад до 0.154 в потерю против прежних 0.060,
    # а это сравнимо с самим обучением. Отсюда и несогласованные сочетания:
    # ему буквально платили за то, чтобы не определяться.
    # 0.0078 возвращает прежнее давление ровно.
    p.add_argument("--svoboda", type=float, default=0.0078,
                   help="бонус за неуверенность (было 0.02 при 20 действиях)")
    # ТОРМОЗ НА ОБУЧЕНИЕ. Главная находка разбора: за ШЕСТЬ обновлений мозга
    # (6600 шагов) изменилось 84% его решений на настоящих кадрах игры. Поворот —
    # на 64%. Работающую политику так швырять нельзя, и это объясняет оба срыва
    # лучше любой арифметики награды: и ночной обвал, и черепаху.
    #
    # Отчего швыряло. У PPO есть штатный тормоз — остановка обновления, когда
    # политика ушла слишком далеко (target_kl). Он был ВЫКЛЮЧЕН (None). При
    # десяти проходах по пачке и отсутствии тормоза одно обновление делает сорок
    # шагов градиента подряд по одним и тем же десяти боям.
    #
    # Три поправки, каждая в свою причину:
    #   povodok  0.02  — сам тормоз: обновление прекращается, когда политика ушла
    #                    на 0.02 по расхождению. Было None, то есть не было.
    #   prohodov 10->4 — меньше переучивания на одной и той же пачке.
    #   pachka 1024->2048 — в пачке будет около двадцати боёв вместо десяти, и
    #                    один неудачный исход перестанет её подавлять.
    # ПОВОДОК БЫЛ В ШЕСТЬ РАЗ СТРОЖЕ, ЧЕМ Я ДУМАЛ. У MultiDiscrete расхождение
    # СКЛАДЫВАЕТСЯ по шести каналам действия: MultiCategoricalDistribution.log_prob
    # это th.stack([...]).sum(dim=1) (distributions.py:351-355), а PPO берёт
    # log_ratio = log_prob - old_log_prob, то есть ту же сумму. Значит 0.02
    # суммарно — это 0.0033 на канал.
    #
    # Тот же множитель шести мы уже нашли для бонуса за неуверенность (энтропия
    # тоже суммируется, и ent_coef пришлось снизить 0.02 -> 0.0078). Для поводка
    # не заметили.
    #
    # 0.12 = 0.02 на каждый из шести каналов. Само по себе это НЕ лечит: при
    # прежнем шаге 2.5e-4 один шаг давал 0.2237, что выше и 1.5*0.12 = 0.18.
    # Лечит уменьшение шага; поводок просто перестаёт врать о том, что мерит.
    # 0.12 -> 0.06 по замеру, а не на глаз. Разметка приборов: train/* пишется
    # на дампе ПОСЛЕ обновления, поэтому дамп на шаге 285599 несёт числа доброго
    # обновления, а 287647 — разрушительного. Сравнение:
    #
    #                        доброе (дало 100%)   разрушительное (дало 61%)
    #     approx_kl              0.0683                 0.1780
    #     clip_fraction          0.3696                 0.4230
    #     policy_gradient_loss  +0.0426                +0.0495
    #     explained_variance    -0.1189                +0.0107
    #
    # Разделяет их ТОЛЬКО путь: 0.068 против 0.178 при пороге обрыва
    # 1.5*0.12 = 0.18. Разрушительное выело поводок ДОТЛА, доброе взяло треть.
    # При 0.06 (обрыв 0.09) доброе проходит нетронутым, разрушительное режется
    # вдвое. Ниже (0.03) опускать не стоит: тогда обрезалось бы и доброе.
    #
    # И важно, чего обрыв НЕ делает: он не отменяет обновление, а останавливает
    # его на полпути — уже сделанные шаги остаются. Поэтому короткий поводок это
    # фильтр: настоящее направление в следующей пачке повторится и доберёт
    # остаток пути, а шум одной пачки не повторится и усреднится.
    p.add_argument("--povodok", type=float, default=0.06,
                   help="тормоз по расхождению политики, СУММА по шести каналам")
    p.add_argument("--prohodov", type=int, default=4,
                   help="проходов по пачке за обновление (было 10)")
    p.add_argument("--pachka", type=int, default=2048,
                   help="шагов на одно обновление (было 1024, это ~10 боёв)")
    # ВЕС ОЦЕНЩИКА. Приборы прогона черепахи: explained_variance -0.07..+0.13,
    # то есть оценщик не объясняет отдачу ВООБЩЕ, а value_loss в конце прогона
    # скакнул 5.5 -> 26.9 -> 46.4. При vf_coef=0.5 это даёт в потерю до 23, тогда
    # как политическая часть порядка 0.05 — в четыреста раз меньше. Ствол зрения у
    # политики и оценщика ОБЩИЙ, значит регрессия непредсказуемой величины
    # перепахивает те самые свёртки, которыми существо находит цель.
    # 0.1 уменьшает это давление впятеро и не требует операции над мозгом.
    p.add_argument("--ves-ocenshchika", type=float, default=0.1,
                   help="вес ошибки оценщика в потере (было 0.5)")
    p.add_argument("--vshivka", type=float, default=None,
                   help="тяга к уроку человека (кадры pokaz/*duel-mechnik*): урок "
                        "предлагает, награда решает. Разбор в telo/vshivka.py")
    p.add_argument("--bez-storozha", action="store_true",
                   help="выключить всех сторожей: для ночного нырка, когда время "
                        "бесплатно, а мозг хранят снимки каждые 1000 шагов")
    p.add_argument("--porog", type=float, default=None,
                   help="порог сторожа на этот прогон (доля убийств); по умолчанию константа")
    p.add_argument("--protiv-cheloveka", action="store_true",
                   help="противник — человек за вторым клиентом, зомби не призывать")
    p.add_argument("--zamorozit-glaz", action="store_true",
                   help="не обучать первый свёрточный слой зрения. После расширения "
                        "224 (дробная интерполяция ядра) обучение растворяло политику "
                        "при ЛЮБЫХ настройках (lr/поводок/свобода вдвое — наклон "
                        "энтропии тот же): градиенты через сглаженное ядро идут "
                        "вразнос. Замороженный глаз смотрит правильно (опора 224 "
                        "это доказала), а читать новые детали учатся слои глубже.")
    args = p.parse_args()
    if args.porog is not None:
        globals()["HUZHE_CHEM"] = args.porog
        print(
            f"порог сторожа на этот прогон: {args.porog:.0%} (передан ночным конвейером)")

    MODELI.mkdir(exist_ok=True)
    if args.protiv_cheloveka:
        A.PROTIV_CHELOVEKA = True
        print("РЕЖИМ БОЯ ПРОТИВ ЧЕЛОВЕКА: зомби не призываются, "
              "убийство человека считается победой")
    print(f"бонус за неуверенность: {args.svoboda} "
          f"(при шести каналах 0.02 давало давление в 2.6 раза сильнее прежнего)")
    print(f"тормоз обучения: поводок {args.povodok}, проходов {args.prohodov}, "
          f"пачка {args.pachka} шагов (~{args.pachka // 100} боёв), "
          f"вес оценщика {args.ves_ocenshchika}. Прежде поводка не было вовсе.")
    print(f"сторож: окно {SLEDIT_ZA_POSLEDNIMI} боёв, стоп при убийствах ниже "
          f"{HUZHE_CHEM:.0%} или при удлинении боёв в {DLINNEE_CHEM} раза. "
          "Прежде судил только с 200-го боя и молчал весь обвал.")
    print(f"ступень лестницы: зомби {A.ZOMBI_NA_ARENE}, доля с мечом "
          f"{A.DOLYA_S_MECHOM:.0%}, здоровье {A.MAX_HEALTH}")
    # Monitor ОБЯЗАТЕЛЕН: именно он ведёт учёт эпизодов, из которого берутся
    # ep_rew_mean и ep_len_mean — главные показатели обучения. Без него первый
    # прогон записал только fps и служебные потери, а средней награды за бой
    # не было вовсе: мы следили за обучением без главного прибора.
    env = DummyVecEnv([lambda: Monitor(M.Bojnya())])

    zip_put = MOZG.with_suffix(".zip")
    # При вшивке урока грузим наследника PPOSUrokom: тот же PPO, но с тягой к
    # уроку в train(). Тождество при тяге 0 доказано пробой proba_vshivki.
    klass = PPO
    if args.vshivka is not None:
        from telo.vshivka import PPOSUrokom
        klass = PPOSUrokom
    if zip_put.exists():
        # Через custom_objects, а не присваиванием после загрузки: PPO.load
        # применяет их ДО _setup_model(), поэтому запас для пачки создаётся уже
        # нужного размера. Присвоить model.n_steps потом — поздно, запас уже есть.
        model = klass.load(MOZG, env=env, device="cuda",
                           custom_objects={"learning_rate": args.lr,
                                           "lr_schedule": (lambda _: args.lr),
                                           "ent_coef": args.svoboda,
                                           "target_kl": args.povodok,
                                           "n_epochs": args.prohodov,
                                           "n_steps": args.pachka,
                                           "vf_coef": args.ves_ocenshchika})
        # PPO.load путь к графикам не восстанавливает
        model.tensorboard_log = str(LOGI)
        # ЗАСЛОН ПРОТИВ НЕСОВПАДЕНИЯ ПАМЯТИ. Я чуть не запустил обучение с мозгом
        # на 12 каналов зрения, когда мир подаёт 24: откатился на снимок, сделанный
        # ДО расширения памяти, и не заметил. Число каналов в имени файла не
        # написано, а по шагам снимки не отличить — оба были на 278503.
        nado_kanalov = 3 * M.KADROV_V_PAMYATI
        est_kanalov = model.observation_space["pov"].shape[0]
        if est_kanalov != nado_kanalov:
            raise SystemExit(
                f"НЕСОВПАДЕНИЕ ПАМЯТИ: мир подаёт {nado_kanalov} каналов зрения "
                f"({M.KADROV_V_PAMYATI} кадров), а мозг ждёт {est_kanalov} "
                f"({est_kanalov // 3} кадров). "
                "Скорее всего мозг откатили на снимок, сделанный до расширения "
                "памяти. Пересобери: rasshirit_pamyat.py")
        if tuple(model.action_space.nvec) != tuple(KAN.KANALY):
            raise SystemExit(
                f"НЕСОВПАДЕНИЕ КАНАЛОВ РЕШЕНИЯ: мозг ждёт "
                f"{list(model.action_space.nvec)}, а чертёж {KAN.KANALY}.")
        print(f"продолжаю с мозга: шагов {model.num_timesteps}, "
              f"зрение {est_kanalov} каналов, решение {list(model.action_space.nvec)}")
        if args.vshivka is not None:
            from telo.vshivka import zagruzit_urok
            u_pov, u_vec, u_act = zagruzit_urok()
            model.nastroit_urok(u_pov, u_vec, u_act, args.vshivka)
            print(f"ВШИВКА УРОКА: тяга {args.vshivka}, кадров урока {len(u_act)} "
                  f"(следи за train/urok — несогласие с человеком должно падать)")
        if args.zamorozit_glaz:
            # Извлекатель у pi/vf общий (один объект), морозим один раз.
            # Adam пропускает веса без градиента — из оптимизатора не вынимаем.
            glaz = model.policy.features_extractor.extractors["pov"].cnn[0]
            for p_ in glaz.parameters():
                p_.requires_grad_(False)
            print(f"ГЛАЗ ЗАМОРОЖЕН: первый свёрточный слой "
                  f"({sum(p_.numel() for p_ in glaz.parameters())} весов) не обучается")
        sbros_schetchika = False
    else:
        raise SystemExit("Мозга нет. Сначала разминка: uchit.bat")

    # СТОРОЖ ТОЛЬКО ПРИ НАСТОЯЩЕМ ОБУЧЕНИИ. При lr=0 (замер опоры) мозг не
    # меняется — защищать нечего, а обрыв замера ИСКАЖАЕТ опору: первая же
    # опора ступени 30 HP была оборвана на 21-м бою (62%), и по обрубку нельзя
    # отличить «слишком круто» от «нормально с шумом». Сторож — страховка
    # обучения, а не судья измерения.
    lenta = Lenta()
    if args.lr == 0.0:
        lenta.storozh_vyklyuchen = True
        print("lr=0: это ЗАМЕР, не обучение — сторож выключен, чтобы не обрывать опору")
    if args.bez_storozha:
        lenta.storozh_vyklyuchen = True
        print("СТОРОЖА ВЫКЛЮЧЕНЫ по флагу: ночной нырок — деградация не будет "
              "остановлена, спасение утром по снимкам (каждые 1000 шагов)")
    kolbeki = [
        # Каждые 1000 шагов, а не 2000: ноут выключают, уходя из дома, и при
        # внезапном выключении терять полчаса обучения незачем. Полтора мегабайта
        # на снимок — дешевле, чем переучивать.
        CheckpointCallback(save_freq=1_000, save_path=str(
            MODELI), name_prefix="ubijca_ckpt"),
        ZamorozkaNaObuchenie(),
        lenta,
    ]
    # Фокуса больше не ждём — мод в нём не нуждается. Но в МИРЕ существо быть
    # обязано: если открыт экран или игрок не зашёл, учиться нечему.
    # Спрашиваем ТЕМ соединением, которое уже открыл мир существа. Своё второе
    # открывать нельзя: у мода один собеседник, и второй молча висит в очереди
    # без ответа. Ровно на этом первый запуск и упал загадочным «timed out».
    env.envs[0].unwrapped.zhdat_gotovnosti()
    print("\nОкно игры может стоять позади других — существо видит игру, а не экран.")
    print("Только не сворачивай его: свёрнутое окно не перерисовывается.")
    print("Пока идёт обучение, не заходи в игру мышью: твоя мышь сложится с его прицелом.")
    print("Пауза — клавиша P в игре. Остановить совсем: Ctrl+C в этом окне.\n")

    kod = 0
    try:
        model.learn(total_timesteps=args.shagov, callback=kolbeki,
                    reset_num_timesteps=sbros_schetchika, progress_bar=True,
                    tb_log_name="UBIJCA")
    except KeyboardInterrupt:
        print("\nостановлено вручную — сохраняю мозг")
    except Exception as e:
        print(f"\nавария ({type(e).__name__}: {e}) — мозг всё равно сохраняю")
        kod = 1
    finally:
        model.save(MOZG)
        print(f"мозг сохранён: {zip_put.name} (шагов {model.num_timesteps})")
        # Разморозить зомби на выходе: последняя заморозка перед train() живёт
        # до следующего on_rollout_start, которого после конца learn() не будет.
        # Иначе зомби стоит статуей до первого сброса следующего запуска.
        try:
            A.zamorozit_vseh(env.envs[0].unwrapped.k, False)
        except Exception:
            pass
        try:
            env.close()
        except Exception:
            pass
    raise SystemExit(kod)


if __name__ == "__main__":
    main()
